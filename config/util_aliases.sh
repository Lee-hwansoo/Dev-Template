# cbuild must be a FUNCTION, not an alias: mksync() calls it, and aliases are
# not expanded inside functions in non-interactive shells (docker build runs
# `bash -lc "... mksync"`). Keep every build entry point callable from scripts.
#
# --symlink-install is a DEVELOPMENT-only optimisation: it symlinks launch files,
# Python modules and resources from src/ into install/ so edits take effect
# without rebuilding. Production images copy only install/ (never src/), so those
# symlinks would dangle in the shipped artifact — DEVKIT_BUILD_TYPE=prod forces a
# real copy. COLCON_EXTRA_FLAGS (already plumbed through compose) is honoured too.
if [ "${ROS_VERSION:-2}" = "2" ]; then
    cbuild() {
        __require_cmd colcon || return 1
        local link_flag=(--symlink-install) extra=()
        [ "${DEVKIT_BUILD_TYPE:-dev}" = "prod" ] && link_flag=()
        [ -n "${COLCON_EXTRA_FLAGS:-}" ] && read -r -a extra <<< "${COLCON_EXTRA_FLAGS}"
        __parse_build_flags 2 "$@" || return 2
        __cmake_extra_args
        # Run from WS_ROOT so build/, install/, log/ and the colcon.meta link
        # land at the workspace root regardless of the caller's cwd.
        ( cd "${WS_ROOT}" && colcon build "${link_flag[@]}" "${extra[@]}" "${DEVKIT_BUILD_SELECT[@]}" \
            --cmake-args -Wno-dev --no-warn-unused-cli \
            -DCMAKE_BUILD_TYPE="${DEVKIT_BUILD_TYPE_ARG}" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
            "${DEVKIT_CMAKE_EXTRA[@]}" "${DEVKIT_BUILD_PASSTHRU[@]}" ) || return 1
        __refresh_links
    }
    alias cbt='colcon test'
    alias cbtr='colcon test-result --all'
    alias rt='ros2 topic list'
    alias rte='ros2 topic echo'
    alias rth='ros2 topic hz'
    alias rn='ros2 node list'
    alias rs='ros2 service list'
    alias rp='ros2 param list'
    alias rr='ros2 run'
    alias rl='ros2 launch'
    alias ri='ros2 interface show'
else
    # catkin_make populates devel/ and build/, never install/. The production
    # runtime image copies install/ only, so a prod build must run the install
    # target explicitly or the shipped image contains no ROS artifacts at all.
    cbuild() {
        __require_cmd catkin_make || return 1
        local extra=()
        [ -n "${COLCON_EXTRA_FLAGS:-}" ] && read -r -a extra <<< "${COLCON_EXTRA_FLAGS}"
        __parse_build_flags 1 "$@" || return 2
        __cmake_extra_args
        set -- "${DEVKIT_BUILD_PASSTHRU[@]}"
        DEVKIT_CMAKE_EXTRA+=("-DCMAKE_BUILD_TYPE=${DEVKIT_BUILD_TYPE_ARG}")
        if [ "${DEVKIT_BUILD_TYPE:-dev}" = "prod" ]; then
            ( cd "${WS_ROOT}" && catkin_make install "${DEVKIT_BUILD_SELECT[@]}" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
                -DCMAKE_INSTALL_PREFIX="${WS_ROOT}/install" "${DEVKIT_CMAKE_EXTRA[@]}" "${extra[@]}" "$@" ) || return 1
            if [ -z "$(find "${WS_ROOT}/install" -mindepth 2 -type f -print -quit 2>/dev/null)" ]; then
                echo -e "  \033[31m[ERROR]\033[0m Production build installed no artifacts into ${WS_ROOT}/install."
                echo -e "  \033[36m[Hint]\033[0m  Add install() rules to your catkin CMakeLists.txt;"
                echo -e "  \033[36m[Hint]\033[0m  the production runtime image copies install/ only."
                return 1
            fi
        else
            ( cd "${WS_ROOT}" && catkin_make "${DEVKIT_BUILD_SELECT[@]}" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
                "${DEVKIT_CMAKE_EXTRA[@]}" "${extra[@]}" "$@" ) || return 1
        fi
        __refresh_links
    }
    alias cbt='catkin_make run_tests'
    alias cbtr='catkin_test_results'
    alias rt='rostopic list'
    alias rte='rostopic echo'
    alias rth='rostopic hz'
    alias rn='rosnode list'
    alias rs='rosservice list'
    alias rp='rosparam list'
    alias rr='rosrun'
    alias rl='roslaunch'
    alias ri='rosmsg show'
fi

# --- Python & Virtualenv (uv) ------------------------------------------------
uvr() { uv run "$@"; }
uvp() { uv pip install "$@"; }
uvl() { uv pip list; }

# uv sync: respects UV_SYNC_FLAGS env var and UV_EXTRA for optional dependency
# groups. A function, not an alias: mksync() calls it non-interactively.
uvs() {
    local venv="${WS_VENV:-${WS_ROOT}/install/.venv}"
    local pyproject="${WS_SRC:-${WS_ROOT}/src}/pyproject.toml"
    local req_file="${WS_ROOT}/dependencies/requirements.txt"
    local sync_flags=()
    [ -n "${UV_SYNC_FLAGS:-}" ] && read -r -a sync_flags <<< "${UV_SYNC_FLAGS}"
    [ -x "${venv}/bin/python" ] || mkenv || return 1

    if [ -f "$pyproject" ]; then
        local extra_args=()
        if [ -n "${UV_EXTRA:-}" ]; then
            extra_args=(--extra "${UV_EXTRA}")
        fi
        # --python pins uv to the interpreter the venv already has. Without it uv
        # compares against UV_PYTHON (3.10 from the image) and REPLACES the venv
        # when they differ — which silently turns the shared venv `mksync --share`
        # just built (noetic, system python) back into a pure one, losing rospy.
        # UV_PROJECT_ENVIRONMENT is not redundant with init_bash.sh either: during
        # `docker build` this runs before /etc/devkit/shell-env.sh exists, so the
        # export is absent and uv would create src/.venv next to pyproject.toml.
        UV_PROJECT_ENVIRONMENT="$venv" \
            uv sync --project "${WS_SRC:-${WS_ROOT}/src}" --python "${venv}/bin/python" \
                "${extra_args[@]}" "${sync_flags[@]}" "$@"
    elif [ -f "$req_file" ] && grep -qv '^[[:space:]]*#' "$req_file" 2>/dev/null; then
        uv pip install --python "${venv}/bin/python" -r "$req_file" "$@"
    else
        echo -e "  \033[34m[INFO]\033[0m No Python dependency manifest found. Skipping uv sync."
    fi
}

# Detect project type: ROS | CPP | PYTHON
# NOTE: `-print -quit` — `-quit` alone is an action, which suppresses find's
# implicit -print and always yields an empty string (silently disabling detection).
__detect_project_type() {
    local src="${WS_SRC:-${WS_ROOT}/src}"
    [ -d "$src" ] || { echo "PYTHON"; return; }
    if [ -n "${ROS_DISTRO:-}" ] && command -v colcon >/dev/null 2>&1; then
        if [ -f "${src}/CMakeLists.txt" ] || [ -n "$(find "$src" -maxdepth 3 -name "package.xml" -print -quit 2>/dev/null)" ]; then
            echo "ROS"; return
        fi
    fi
    if [ -n "$(find "$src" -maxdepth 3 -name "CMakeLists.txt" -print -quit 2>/dev/null)" ]; then
        echo "CPP"
    else
        echo "PYTHON"
    fi
}

# The venv is NAMED after the project (`(myproject-lee)`) instead of after its
# directory, so one glance tells which workspace a shell belongs to. Trailing
# arguments reach `uv venv`, so `mkenv --link-mode copy` works.
mkenv() {
    local venv_dir="${WS_VENV:-${WS_ROOT}/install/.venv}"
    local prompt="${COMPOSE_PROJECT_NAME:-.venv}"
    local share=() py="${UV_PYTHON:-3.10}" label="Pure"
    __parse_share_flag "$@"
    if [ "$DEVKIT_SHARE_MODE" = true ]; then
        share=(--system-site-packages); py="${SYS_PYTHON_EXE}"; label="Shared"
    fi
    if command -v uv >/dev/null 2>&1; then
        uv venv "$venv_dir" --python "$py" "${share[@]}" --seed \
            --prompt "$prompt" "${DEVKIT_REMAINING_ARGS[@]}" || return 1
    else
        # The fallback must honour --share too, or a noetic workspace (where it
        # is forced) silently ends up without rospy.
        python3 -m venv "${share[@]}" --prompt "$prompt" "$venv_dir" || return 1
    fi
    __refresh_links   # ${WS_ROOT}/.venv should point at the new environment now
    echo -e "  \033[32m[OK]\033[0m ${label} venv '${prompt}' created: ${venv_dir}"
    source "${venv_dir}/bin/activate"
}

activate() {
    local venv_dir="${WS_VENV:-${WS_ROOT}/install/.venv}"
    if [ -f "${venv_dir}/bin/activate" ]; then
        source "${venv_dir}/bin/activate"
        # Re-entrant with no help from us: both uv's and CPython's activate call
        # `deactivate nondestructive` first, restoring PATH before re-prefixing.
        # Same normalisation as config/init_bash.sh: one pair of parens either way.
        VIRTUAL_ENV_PROMPT="${VIRTUAL_ENV_PROMPT#\(}"; VIRTUAL_ENV_PROMPT="${VIRTUAL_ENV_PROMPT%\) }"
        echo -e "  \033[32m[OK]\033[0m Activated virtualenv: ${venv_dir}"
    else
        echo -e "  \033[33m[WARN]\033[0m Virtualenv not found at ${venv_dir}. Run 'mkenv' first."
    fi
}

alias sync_deps='bash ${WS_SCRIPTS}/setup_sync_deps.sh'

mksync() {
    __parse_share_flag "$@"
    local mkenv_args=()
    [ "$DEVKIT_SHARE_MODE" = true ] && mkenv_args=(--share)
    # Snapshot now: mkenv() re-runs __parse_share_flag and overwrites the globals.
    local uvs_args=("${DEVKIT_REMAINING_ARGS[@]}")

    # 1. venv → activate → Python packages → system/ROS dependencies
    mkenv "${mkenv_args[@]}" && \
    uvs "${uvs_args[@]}" && \
    bash "${WS_SCRIPTS}/setup_sync_deps.sh" --rosdep || return 1

    # 2. Build with whatever the project layout calls for
    local project_type
    project_type=$(__detect_project_type)
    case "$project_type" in
        "ROS")
            echo -e "  \033[34m[INFO]\033[0m ROS workspace detected — building..."
            cbuild && __smart_source ;;
        "CPP")
            echo -e "  \033[34m[INFO]\033[0m Pure C++ project detected — running mbuild..."
            mbuild ;;
        *)
            echo -e "  \033[32m[OK]\033[0m Pure Python project — no build step needed." ;;
    esac
}

# pyv: one-glance answer to "which python am I actually running?"
pyv() {
    printf '  %-11s: %s (%s)\n' "python3" "$(command -v python3)" "$(python3 -V 2>&1 | cut -d' ' -f2)"
    printf '  %-11s: %s\n' "venv" "${VIRTUAL_ENV:-inactive}"
    command -v uv >/dev/null 2>&1 && printf '  %-11s: %s\n' "uv" "$(uv --version 2>/dev/null | cut -d' ' -f2)"
    python3 -c 'import sys; print("  {:<11}: {}".format("sys.prefix", sys.prefix))' 2>/dev/null
}

uvpython() {
    local venv_py="${WS_VENV:-${WS_ROOT}/install/.venv}/bin/python3"
    if [ -f "$venv_py" ]; then
        "$venv_py" "$@"
    else
        python3 "$@"
    fi
}

syspython() {
    /usr/bin/python3 "$@"
}

