# --- Hardware & GPU Diagnostics ---------------------------------------------
gpu() {
    local mode="${1:-status}"
    case "$mode" in
        status|opencv_args|auto|nvidia|tegra|intel|amd|igpu|cpu)
            source "${WS_SCRIPTS}/setup_gpu.sh" "$mode"
            ;;
        *)
            echo "Usage: gpu {status|opencv_args|auto|nvidia|tegra|intel|amd|igpu|cpu}"
            return 1
            ;;
    esac
}

alias gpu_check='glxinfo 2>&1 | grep -E "OpenGL (vendor|renderer|version)" || echo "No display / glxinfo unavailable"'
alias vulkan_check='vulkaninfo --summary 2>/dev/null | head -20 || echo "Vulkan not available"'

# gpu_test: actually RENDER something. `gpus`/`gpu_check` report what the stack
# claims; this proves frames are produced and at what rate — the difference
# between "configured" and "working". Vendor- and framework-agnostic.
gpu_test() {
    if ! command -v glxgears >/dev/null 2>&1; then
        echo -e "  \033[33m[WARN]\033[0m glxgears not installed (apt: mesa-utils)."; return 1
    fi
    if [ -z "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ]; then
        echo -e "  \033[33m[WARN]\033[0m No DISPLAY/WAYLAND_DISPLAY — cannot render."; return 1
    fi
    echo -e "  \033[34m[INFO]\033[0m Rendering for 5s..."
    local out
    out="$(timeout 6 glxgears -info 2>&1 | grep -E "GL_RENDERER|frames in" | head -3 || true)"
    if [ -z "$out" ]; then
        echo -e "  \033[31m[ERROR]\033[0m No frames rendered — check 'gpus' and 'make xauth'."; return 1
    fi
    echo "$out" | sed 's/^/    /'
}

# torch_check / pyt: the first question after a GPU setup is whether the ML
# stack actually sees the device. Reports gracefully when torch is absent.
torch_check() {
    local py="${WS_VENV:-${WS_ROOT}/install/.venv}/bin/python3"
    [ -x "$py" ] || py=python3
    "$py" - <<'PY' 2>/dev/null || echo -e "  \033[33m[WARN]\033[0m PyTorch not installed (run: uvs, or set UV_EXTRA=gpu)."
import torch
print(f"    torch      {torch.__version__}")
print(f"    CUDA build {torch.version.cuda or 'cpu-only'}")
avail = torch.cuda.is_available()
print(f"    CUDA avail {avail}")
if avail:
    print(f"    device     {torch.cuda.get_device_name(0)}")
elif getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
    print("    device     Apple MPS")
PY
}
alias pyt='torch_check'

# --- Modern CMake & C++ Shortcuts --------------------------------------------
mbuild() {
    # Source root: repository root if it carries the top-level CMakeLists.txt,
    # otherwise src/ (the layout __detect_project_type reports as CPP).
    local src_dir="${WS_ROOT}"
    if [ ! -f "${WS_ROOT}/CMakeLists.txt" ]; then
        src_dir="${WS_SRC:-${WS_ROOT}/src}"
    fi
    if [ ! -f "${src_dir}/CMakeLists.txt" ]; then
        echo -e "  \033[31m[ERROR]\033[0m No CMakeLists.txt found in ${WS_ROOT} or ${src_dir}."
        return 1
    fi
    __require_cmd cmake || return 1
    __parse_build_flags cmake "$@" || return 2
    __cmake_extra_args
    cmake -B "${WS_ROOT}/build" -S "$src_dir" -Wno-dev --no-warn-unused-cli \
          -DCMAKE_BUILD_TYPE="${DEVKIT_BUILD_TYPE_ARG}" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
          -DCMAKE_INSTALL_PREFIX="${WS_ROOT}/install" "${DEVKIT_CMAKE_EXTRA[@]}" "${DEVKIT_BUILD_PASSTHRU[@]}" \
        && cmake --build "${WS_ROOT}/build" -j"$(nproc 2>/dev/null || echo 4)" || return 1
    __refresh_links

    # Production images copy install/ and never build/, so a prod build MUST
    # install. Without this a C++ prod image ships no executable at all.
    if [ "${DEVKIT_BUILD_TYPE:-dev}" = "prod" ]; then
        cmake --install "${WS_ROOT}/build" || return 1
        if [ -z "$(find "${WS_ROOT}/install" -mindepth 2 -type f -print -quit 2>/dev/null)" ]; then
            echo -e "  \033[31m[ERROR]\033[0m Production build installed no artifacts into ${WS_ROOT}/install."
            echo -e "  \033[36m[Hint]\033[0m  Add install(TARGETS ... DESTINATION bin/lib) rules to your CMakeLists.txt;"
            echo -e "  \033[36m[Hint]\033[0m  the production runtime image copies install/ only."
            return 1
        fi
    fi
}

# ${WS_ROOT:?}: util_paths.sh is sourced with `|| true` above — if it failed,
# an unset WS_ROOT would make this rm -rf /build /log … instead of erroring.
# build/install/log are named-volume MOUNT POINTS in the dev container: rm -rf
# empties them but cannot remove the directory itself (EBUSY) — expected, so
# stderr is suppressed. The find afterwards distinguishes that benign case from
# real failures (permissions, root-owned files): leftover CONTENT means failure.
mclean() {
    local dirs=("${WS_ROOT:?}/build" "${WS_ROOT:?}/log" "${WS_ROOT:?}/install/bin" "${WS_ROOT:?}/install/lib")
    local what="build, log and install output directories (--all removes install/ too)"
    if [ "${1:-}" = "--all" ]; then
        dirs=("${WS_ROOT:?}/build" "${WS_ROOT:?}/log" "${WS_ROOT:?}/devel" "${WS_ROOT:?}/install")
        what="ALL build output including install/ and the virtualenv (re-run mksync)"
    fi
    rm -rf "${dirs[@]}" 2>/dev/null || true
    if [ -n "$(find "${dirs[@]}" -mindepth 1 -print -quit 2>/dev/null)" ]; then
        echo -e "  \033[31m[ERROR]\033[0m Some entries could not be removed (root-owned? permissions?)."
        echo -e "  \033[36m[Hint]\033[0m  Inspect with: ls -la ${WS_ROOT:?}/build ${WS_ROOT:?}/install"
        return 1
    fi
    echo -e "  \033[32m[OK]\033[0m Emptied ${what}."
}

