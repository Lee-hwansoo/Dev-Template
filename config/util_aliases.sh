# Shared CMake knobs (.env → compose → here): CMAKE_EXTRA_ARGS, the documented
# C/C++ standard pins and the OPENCV_CUDA policy. Fills DEVKIT_CMAKE_EXTRA.
__cmake_extra_args() {
    DEVKIT_CMAKE_EXTRA=()
    [ -n "${CMAKE_EXTRA_ARGS:-}" ] && read -r -a DEVKIT_CMAKE_EXTRA <<< "${CMAKE_EXTRA_ARGS}"
    [ -n "${CMAKE_C_STANDARD:-}" ] && DEVKIT_CMAKE_EXTRA+=("-DCMAKE_C_STANDARD=${CMAKE_C_STANDARD}")
    [ -n "${CMAKE_CXX_STANDARD:-}" ] && DEVKIT_CMAKE_EXTRA+=("-DCMAKE_CXX_STANDARD=${CMAKE_CXX_STANDARD}")
    # OPENCV_CUDA reaches the compiler here, not just `gpu opencv_args`: a project
    # that builds OpenCV from source needs the flags at configure time. Probed per
    # call on purpose — 90 ms against a build measured in seconds is not worth a
    # cache to invalidate.
    local gpu_args=()
    read -r -a gpu_args <<< "$(bash "${WS_SCRIPTS}/setup_gpu.sh" opencv_args 2>/dev/null || true)"
    DEVKIT_CMAKE_EXTRA+=("${gpu_args[@]}")
    return 0
}

# A missing build tool means the wrong image, not a broken workspace — say which.
__require_cmd() {
    command -v "$1" >/dev/null 2>&1 && return 0
    echo -e "  \033[31m[ERROR]\033[0m '$1' not found in this image." >&2
    echo -e "  \033[36m[Hint]\033[0m  ROS builds need ENV=ros; plain CMake projects use 'mbuild'." >&2
    return 1
}

# ${WS_ROOT}/.venv, colcon.meta and compile_commands.json are regenerated by the
# same script config/init_bash.sh runs at shell start; call it after anything
# that creates their targets so the links do not lag a whole session behind.
__refresh_links() {
    [ -x "${WS_SCRIPTS}/util_setup_links.sh" ] && "${WS_SCRIPTS}/util_setup_links.sh" --skip-compile-commands
    return 0
}

# The build flags the MOTD advertises: --debug/--release/--pkg/--meta, with
# everything else passed through untouched ('--' forces passthrough). $1 selects
# the generation, because the package selector differs per tool:
#   2 = colcon (--packages-select, --metas), 1 = catkin_make (--only-pkg-with-deps),
#   cmake = plain CMake, where neither applies.
# Fills DEVKIT_BUILD_TYPE_ARG / DEVKIT_BUILD_SELECT / DEVKIT_BUILD_PASSTHRU.
__parse_build_flags() {
    local gen="${1:-2}"; shift
    # RelWithDebInfo, not CMake's empty default: an unoptimised robotics build is
    # a performance bug nobody reads in the log.
    DEVKIT_BUILD_TYPE_ARG="RelWithDebInfo"
    DEVKIT_BUILD_SELECT=()
    DEVKIT_BUILD_PASSTHRU=()
    while [ $# -gt 0 ]; do
        case "$1" in
            --debug)   DEVKIT_BUILD_TYPE_ARG="Debug"; shift ;;
            --release) DEVKIT_BUILD_TYPE_ARG="Release"; shift ;;
            --pkg)
                shift
                if [ $# -eq 0 ] || [[ "$1" == --* ]]; then
                    echo -e "  \033[31m[ERROR]\033[0m --pkg requires at least one package name." >&2
                    return 2
                fi
                case "$gen" in
                    2) DEVKIT_BUILD_SELECT+=(--packages-select) ;;
                    1) DEVKIT_BUILD_SELECT+=(--only-pkg-with-deps) ;;
                    *) echo -e "  \033[31m[ERROR]\033[0m --pkg applies to ROS builds only." >&2; return 2 ;;
                esac
                while [ $# -gt 0 ] && [[ "$1" != --* ]]; do DEVKIT_BUILD_SELECT+=("$1"); shift; done ;;
            --meta)
                if [ "$gen" = "2" ]; then
                    DEVKIT_BUILD_SELECT+=(--metas "${WS_CONFIG:-${WS_ROOT}/config}/colcon.meta")
                else
                    echo -e "  \033[33m[WARN]\033[0m --meta is a colcon option; ignored here." >&2
                fi; shift ;;
            --) shift; DEVKIT_BUILD_PASSTHRU+=("$@"); break ;;
            *)  DEVKIT_BUILD_PASSTHRU+=("$1"); shift ;;
        esac
    done
}

# Parse --share flag; auto-enable for ROS 1 Noetic (tied to system Python ABI)
__parse_share_flag() {
    DEVKIT_SHARE_MODE=false
    DEVKIT_REMAINING_ARGS=()
    for arg in "$@"; do
        case "$arg" in
            --share) DEVKIT_SHARE_MODE=true ;;
            *) DEVKIT_REMAINING_ARGS+=("$arg") ;;
        esac
    done
    [ "${ROS_DISTRO:-}" = "noetic" ] && DEVKIT_SHARE_MODE=true
}

